"""Make the locked environment of each native process group.

A process group runs several Python services in one interpreter
(``native_group.py``). Its environment must satisfy every member's declared
requirements at once. This script writes ``groups/<group>/pyproject.toml``
from the members' ``pyproject.toml`` files: the project dependencies plus the
dependency groups each member's Dockerfile installs. Each package is limited
to the highest version that a member's own ``uv.lock`` uses, so the group
runs versions the services were tested with. ``uv lock`` then solves all the
limits together, and the lock file is kept in the checkout.

    python merge_groups.py           # write the group projects
    python merge_groups.py --check   # exit 1 when a group project is stale

After a write, run ``uv lock`` in each changed group folder.
"""
from __future__ import annotations

import pathlib
import sys
import tomllib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]

#: group -> [(member project, dependency groups its Dockerfile installs)]
GROUPS = {
    "core": [
        ("core/identity/services/admin-api", ["production"]),
        ("core/meetings/services/meeting-api", ["production"]),
        ("core/gateway/services/gateway", ["production"]),
        ("core/gateway/services/mcp", ["production"]),
        ("core/agent/services/credential-broker", []),
        ("core/crm", []),
        ("core/flows", []),
    ],
}


def requirements(project: str, groups: list[str]) -> list[str]:
    data = tomllib.loads((REPO / project / "pyproject.toml").read_text())
    out = list(data["project"].get("dependencies", []))
    for group in groups:
        out += [r for r in data.get("dependency-groups", {}).get(group, []) if isinstance(r, str)]
    return out


def _version_key(version: str) -> tuple:
    parts = []
    for piece in version.replace("-", ".").split("."):
        parts.append((0, int(piece)) if piece.isdigit() else (1, piece))
    return tuple(parts)


def locked_ceilings(group: str) -> dict[str, str]:
    """For each package, the highest version that a member's own lock uses.

    The group environment must not be newer than the versions the services
    were tested with, so each one becomes an upper constraint.
    """
    ceilings: dict[str, str] = {}
    for project, _ in GROUPS[group]:
        lock = tomllib.loads((REPO / project / "uv.lock").read_text())
        for package in lock.get("package", []):
            name, version = package["name"], package.get("version")
            if not version or package.get("source", {}).get("virtual") or package.get("source", {}).get("editable"):
                continue
            if name not in ceilings or _version_key(version) > _version_key(ceilings[name]):
                ceilings[name] = version
    return ceilings


def render(group: str) -> str:
    members = GROUPS[group]
    lines = [
        "# Generated by apps/vexa-daemon/python/merge_groups.py. Do not edit.",
        f"# The {group} process group: " + ", ".join(m for m, _ in members) + ".",
        "[project]",
        f'name = "vexa-native-{group}"',
        'version = "0.0.0"',
        'requires-python = ">=3.12,<3.13"',
        "dependencies = [",
    ]
    for project, groups in members:
        lines.append(f"    # {project}")
        lines += [f'    "{req}",' for req in requirements(project, groups)]
    lines += ["]", "", "[tool.uv]", "package = false", "# Not newer than any member lock (locked_ceilings).", "constraint-dependencies = ["]
    lines += [f'    "{name}<={version}",' for name, version in sorted(locked_ceilings(group).items())]
    lines += ["]", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for group in GROUPS:
        target = HERE / "groups" / group / "pyproject.toml"
        text = render(group)
        if target.exists() and target.read_text() == text:
            continue
        if check:
            stale.append(str(target.relative_to(REPO)))
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        print(f"wrote {target.relative_to(REPO)}; run `uv lock` in {target.parent.relative_to(REPO)}")
    if stale:
        print("stale group projects (run merge_groups.py, then uv lock): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
